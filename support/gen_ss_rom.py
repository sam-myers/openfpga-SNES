#!/usr/bin/env python3
"""Convert an assembled savestates.bin into rtl/mister_top/ss_rom.sv.

The savestate engine fetches its 65816 routine from ROM bank $FF, offset {ca[16], ca[14:0]}, which is
the byte offset into savestates.bin. The generated module is a 16-bit wide ROM indexed by word address,
little endian (low byte = even address), matching how SDRAM returns ROM words.

Usage: gen_ss_rom.py savestates.bin ss_rom.sv
"""
import sys

MAX_BYTES = 0x10000


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)

    with open(sys.argv[1], "rb") as f:
        data = f.read()

    if not data:
        sys.exit("savestates.bin is empty")
    if len(data) > MAX_BYTES:
        sys.exit(f"savestates.bin is {len(data)} bytes, larger than the 64KB bank")

    if len(data) % 2:
        data += b"\x00"

    words = len(data) // 2
    addr_width = max(1, (words - 1).bit_length())
    depth = 1 << addr_width

    lines = [
        "// GENERATED by support/gen_ss_rom.py from savestates.bin. Do not edit",
        f"// {len(data)} bytes",
        "module ss_rom (",
        "    input wire clk,",
        "    input wire [14:0] addr,",
        "    output reg [15:0] q",
        ");",
        f"  reg [15:0] rom[0:{depth - 1}];",
        "",
        "  initial begin",
    ]

    for i in range(depth):
        word = data[2 * i] | (data[2 * i + 1] << 8) if i < words else 0
        lines.append(f"    rom[{i}] = 16'h{word:04X};")

    lines += [
        "  end",
        "",
        "  always @(posedge clk) begin",
        f"    q <= rom[addr[{addr_width - 1}:0]];",
        "  end",
        "endmodule",
        "",
    ]

    with open(sys.argv[2], "w") as f:
        f.write("\n".join(lines))

    print(f"Wrote {sys.argv[2]}: {len(data)} bytes, {depth} words")


if __name__ == "__main__":
    main()
